// Generates plugin/src/ApiDump.luau — a whitelist of serializable, scriptable
// properties per GUI-relevant class, resolved through the superclass chain.
// Rerun when Roblox adds new properties:  node tools/generate-api-dump.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const DUMP_URL =
	"https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json";

const CLASS_WHITELIST = [
	// GUI containers
	"ScreenGui",
	"BillboardGui",
	"SurfaceGui",
	"Frame",
	"ScrollingFrame",
	"CanvasGroup",
	"ViewportFrame",
	"VideoFrame",
	"TextLabel",
	"TextButton",
	"TextBox",
	"ImageLabel",
	"ImageButton",
	// UI modifiers / layouts / constraints
	"UICorner",
	"UIStroke",
	"UIGradient",
	"UIPadding",
	"UIScale",
	"UIAspectRatioConstraint",
	"UISizeConstraint",
	"UITextSizeConstraint",
	"UIListLayout",
	"UIGridLayout",
	"UITableLayout",
	"UIPageLayout",
	"UIFlexItem",
	// Scripts (for Disabled/RunContext metadata)
	"Script",
	"LocalScript",
	"ModuleScript",
	// Misc things commonly stored inside GUIs
	"Folder",
	"Configuration",
	"Camera",
	"Sound",
	"StringValue",
	"BoolValue",
	"NumberValue",
	"IntValue",
	"Color3Value",
	"Vector3Value",
];

// Properties that can never round-trip through this pipeline.
const PROPERTY_BLACKLIST = new Set(["Name", "Parent", "Archivable", "Source"]);
const EXCLUDED_TAGS = new Set(["ReadOnly", "NotScriptable", "Deprecated", "Hidden"]);
// Value-type categories we cannot encode (instance refs, binary blobs).
const EXCLUDED_TYPE_CATEGORIES = new Set(["Class"]);
const EXCLUDED_TYPE_NAMES = new Set(["BinaryString", "SharedString", "SecurityCapabilities", "UniqueId"]);
// Plugins run at PluginSecurity, and Argon writes properties via rbx-dom
// (no security checks), so PluginSecurity members are readable/writable here.
const ALLOWED_SECURITY = new Set(["None", "PluginSecurity"]);

const res = await fetch(DUMP_URL);
if (!res.ok) throw new Error(`Failed to download API dump: ${res.status}`);
const dump = await res.json();

const classesByName = new Map(dump.Classes.map((c) => [c.Name, c]));

function collectProperties(className) {
	const names = [];
	let cls = classesByName.get(className);
	while (cls) {
		for (const member of cls.Members ?? []) {
			if (member.MemberType !== "Property") continue;
			if (PROPERTY_BLACKLIST.has(member.Name)) continue;
			const tags = member.Tags ?? [];
			if (tags.some((t) => EXCLUDED_TAGS.has(t))) continue;
			const ser = member.Serialization ?? {};
			if (!ser.CanSave || !ser.CanLoad) continue;
			const sec = member.Security ?? {};
			if (!ALLOWED_SECURITY.has(sec.Read) || !ALLOWED_SECURITY.has(sec.Write)) continue;
			const vt = member.ValueType ?? {};
			if (EXCLUDED_TYPE_CATEGORIES.has(vt.Category)) continue;
			if (EXCLUDED_TYPE_NAMES.has(vt.Name)) continue;
			names.push(member.Name);
		}
		cls = classesByName.get(cls.Superclass);
	}
	return [...new Set(names)].sort();
}

let out = "-- Generated by tools/generate-api-dump.mjs — do not edit manually.\n";
out += "-- Serializable, scriptable properties per class (superclasses resolved).\n";
out += "return {\n";
for (const className of CLASS_WHITELIST) {
	if (!classesByName.has(className)) {
		console.warn(`WARN: class not found in API dump: ${className}`);
		continue;
	}
	const props = collectProperties(className);
	out += `\t${className} = {\n`;
	for (const p of props) out += `\t\t"${p}",\n`;
	out += "\t},\n";
}
out += "}\n";

const outPath = join(dirname(fileURLToPath(import.meta.url)), "..", "plugin", "src", "ApiDump.luau");
writeFileSync(outPath, out);
console.log(`Wrote ${outPath}`);
